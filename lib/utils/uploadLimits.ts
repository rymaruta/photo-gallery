/**
 * 1人あたりのアップロード上限（画面側の写し）。
 *
 * **`api-user/src/photoLimit.ts` の `PHOTO_LIMIT_PER_USER` と対。**
 * クライアントから api-user は import できない（別パッケージ・別ビルド）ので
 * 数字を2か所に持つことになる。片方だけ変えると
 *   - 画面が大きい  → 「あと N 枚」と出ているのに押すと 403
 *   - 画面が小さい  → 上げたのに投稿できないままに見える
 * のどちらかになるので、`scripts/__tests__/limitParity.test.ts` が
 * 数字そのものを突き合わせる。
 *
 * **画面のファイルの中に直接書かない**（前はそうだった）。テストが
 * 文言の中の数字を手書きすることになり、上限を動かすたびに
 * 「テストを実装に合わせて直す」形になる。
 *
 * 2026-09-09 に 100 → 1000 へ（owner の判断）。
 * **注意: 一覧はまだ全件を返す。** `GET /photos` は公開写真を全部返し、
 * 同じ量が静的バンドルにも埋まっている（実測 30枚=21KB / 3,000枚=140KB・
 * どちらも gzip）。**300〜500枚に近づく前にページングを入れること**
 * ——この上限はそれまでの余裕であって、耐えられる保証ではない。
 */
export const PHOTO_LIMIT_PER_USER = 1000;

/**
 * **1投稿に入れられる写真の枚数**（表紙 + 2枚目以降）。画面側の写し。
 *
 * **`api-user/src/photoImages.ts` の `PHOTO_IMAGES_MAX` と対。**
 * クライアントから api-user は import できない（`app/` から import すると
 * `next build` が落ちる。`7276c2b8` で踏んだ）ので数字を2か所に持つことになる。
 * 片方だけ変えると
 *   - 画面が大きい  → 11枚目以降が**黙って落ちる**（保存は成功して、あとで
 *                     開くと足りない）
 *   - 画面が小さい  → サーバーは受け付けるのに選べない
 * のどちらかになるので、`scripts/__tests__/limitParity.test.ts` が突き合わせる。
 *
 * 10 は owner のモック（投稿作成の「1/10」）から。
 */
export const PHOTO_IMAGES_MAX = 10;
