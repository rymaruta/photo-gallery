/**
 * **`sizes` は「実際に描かれる幅」を申告する。** ずれるとブラウザが選ぶ候補が
 * 変わる——大きく申告すれば無駄に重い方を、小さく申告すればぼやける方を落とす。
 *
 * 以前は `GalleryGrid` が `"(max-width:640px) 50vw, (max-width:1024px) 33vw, 25vw"`
 * を**決め打ち**していたが、この部品は**幅の違う容器で使い回されている**
 * （ホーム/お気に入りは `max-w-5xl`・集約ページは `max-w-6xl`）。しかも
 * `25vw` は容器の上限を無視するので、画面が広いほど申告だけが伸びる。
 *
 * 実測（Chromium・トップページ）:
 *
 *     画面 1280px  申告 320px  実際 236px   → 256px の候補が一度も選ばれない
 *     画面 1536px  申告 384px  実際 236px
 *     ちょうど 640px 申告 320px 実際 193px  ← Tailwind の `sm:` は 640 **から**
 *                                             効くのに `max-width:640px` も 640 を含む
 *
 *     選ばれた候補（30枚・DPR1 のデスクトップ）  256w: 0件 / 512w: 30件
 *
 * DPR2 以上では 512 が正しい選択なので、ここが効くのは **DPR1 のデスクトップ**。
 * 箱が 236px なら 256px の候補で足りる（画素数で4倍・合成画像での実測で
 * webp 2.7倍 / avif 2.3倍のバイト）。
 *
 * ## 単位が2種類あるのは、基準が2つあるから（どちらも実測）
 *
 * **Tailwind v4 は全部 rem。** 出力された CSS を読むと
 * `@media (min-width:40rem)` ・ `--spacing:.25rem` ・ `--container-5xl:64rem`。
 * つまり利用者がブラウザの既定フォントを大きくすると、**折り返す幅も余白も
 * 容器の上限も一緒に伸びる**。
 *
 * **`sizes` の中の rem は「ブラウザの既定」で解ける**（条件も長さも）。
 * これは Tailwind のメディアクエリと同じ土俵なので、**rem で書けば追随する**。
 *
 * 以前は 640px 未満だけ px の行を先に置いていた——`app/globals.css` が電話の幅で
 * `html{font-size:14px}` を当てていて、余白が 14px・隙間が 3.5px で固定されていたため
 * （画面390px のセル 179.25px）。**2026-10-30（束 0a）にその規則を外した**ので、
 * 640px 未満も root は 16px＝rem の行がそのまま当たる。px の行は消した。
 *
 *     画面390px   余白16 / 隙間4  / セル (390 - 32 - 4) / 2 = 177
 *     画面1280px  余白32 / 隙間6  / セル (1024 - 64 - 18) / 4 = 235.5
 *
 * 境界は Tailwind の手前で切る（`39.99rem`）。`640px` と書くと 640 ちょうどで
 * 食い違う（`sm:` は 640 **から**効くのに `max-width:640px` も 640 を含む）。
 */
export const GRID_SIZES_5XL = [
    "(max-width:39.99rem) calc(50vw - 1.125rem)",    // 2列 / root はブラウザ既定（余白1rem×2・隙間0.25rem）
    "(max-width:47.99rem) calc(33.33vw - 1.25rem)",  // 3列 / p-6（1.5rem×2）・隙間0.375rem×2
    "(max-width:63.99rem) calc(33.33vw - 1.583rem)", // 3列 / p-8（2rem×2）・隙間0.375rem×2
    "14.71875rem",                                   // 4列 / 容器 64rem で頭打ち: (64 - 4 - 1.125) / 4
].join(", ");

